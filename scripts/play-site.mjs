#!/usr/bin/env node
// Sprint 15 (S-15-5): assembles the play site that the android workflow's
// `site` job force-pushes to the orphan `play` branch (Netlify's production
// branch, https://overcloc.netlify.app). Input: the built web game
// (apps/client/dist, BASE_PATH=/) and the checked APK. Adds
//   app/overclock.apk     — the newest app under a fixed name (demo-note link)
//   app/<apk>             — the same file under its build name
//   app/latest.json       — {buildTime, versionCode, branch, commit, apk}
//   netlify.toml          — no build; APK download headers
// `scripts/check-site.mjs` then checks the result independently.
//
// Usage: node scripts/play-site.mjs <siteDir> <apkFile>
//   env BUILD_TIME, VERSION_CODE, BRANCH, GITHUB_SHA (the build's values).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const APK_TYPE = 'application/vnd.android.package-archive';

/** The `netlify.toml` of the `play` branch: publish as is, never build. */
export function netlifyToml(apkName) {
  const apkHeaders = (file) => [
    '[[headers]]',
    `  for = "/app/${file}"`,
    '  [headers.values]',
    `    Content-Type = "${APK_TYPE}"`,
    `    Content-Disposition = "attachment; filename=\\"${file}\\""`,
    '    Cache-Control = "no-cache"',
    '',
  ];
  return [
    '# Generated by scripts/play-site.mjs (android workflow, `site` job). Do not edit:',
    '# every publish replaces this branch. The site is already built, so Netlify',
    '# only publishes it (no install, no build).',
    '[build]',
    '  publish = "."',
    '  command = "echo The play branch is a prebuilt site: nothing to build."',
    '',
    ...apkHeaders('overclock.apk'),
    ...(apkName === 'overclock.apk' ? [] : apkHeaders(apkName)),
    '[[headers]]',
    '  for = "/app/latest.json"',
    '  [headers.values]',
    '    Cache-Control = "no-cache"',
    '',
  ].join('\n');
}

/** `app/latest.json`: what the start screen's "Get the Android app" button reads. */
export function latestJson({ buildTime, versionCode, branch, commit, apk }) {
  return `${JSON.stringify({ buildTime, versionCode: Number(versionCode), branch, commit, apk }, null, 2)}\n`;
}

export function assemble(siteDir, apkFile, meta) {
  const apk = basename(apkFile);
  const app = join(siteDir, 'app');
  mkdirSync(app, { recursive: true });
  copyFileSync(apkFile, join(app, 'overclock.apk'));
  copyFileSync(apkFile, join(app, apk));
  writeFileSync(join(app, 'latest.json'), latestJson({ ...meta, apk }));
  writeFileSync(join(siteDir, 'netlify.toml'), netlifyToml(apk));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [siteDir, apkFile] = process.argv.slice(2);
  const env = process.env;
  const missing = ['BUILD_TIME', 'VERSION_CODE', 'BRANCH', 'GITHUB_SHA'].filter((k) => !env[k]);
  if (!siteDir || !apkFile || missing.length) {
    console.error(`usage: play-site.mjs <siteDir> <apkFile> (env BUILD_TIME, VERSION_CODE, BRANCH, GITHUB_SHA)${missing.length ? `; missing ${missing.join(', ')}` : ''}`);
    process.exit(2);
  }
  assemble(siteDir, apkFile, { buildTime: env.BUILD_TIME, versionCode: env.VERSION_CODE, branch: env.BRANCH, commit: env.GITHUB_SHA });
  console.log(`play site assembled in ${siteDir} with app/${basename(apkFile)}`);
}
